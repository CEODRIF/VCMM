"""Clip persistence for the analysis stage (Phase 4).

Writes the detected clips into the EXISTING ``public.clips`` table:

- ``title``, ``start_time``, ``end_time``, ``sort_order``, ``score`` and
  ``scoring`` (the explainable breakdown) are stored per clip;
- ``duration`` is a GENERATED column (end_time - start_time) and is
  rejected by ``clips_duration_bounds`` (60-180s) if the detector ever
  emitted an out-of-band window;
- the write is DELETE-THEN-INSERT **scoped to the single job_id**, so a
  retried analysis replaces only its own clips and can never touch
  another job's rows (RLS + scoping + the job FK all agree).

Phase 5 adds the rendering-side access: ``list_clips`` (read the job's clip
set in sort order) and ``mark_clip`` (move ONE clip of ONE job to
``processing``/``ready`` — every update is scoped to ``(id, job_id)`` so a
stale worker can never touch another job's clips). ``storage_path`` is set
when a clip is rendered AND stored — that is what the DB completion guard
(``complete_job_rendering``) requires.
"""

from __future__ import annotations

import logging
import re
from typing import Any
from uuid import UUID

from supabase import Client

from ..ai.clip_detection import ScoredClip

logger = logging.getLogger("clipforge.clips")

CLIPS_TABLE = "clips"

_UUID_RE = re.compile(r"^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$")

#: The only clip statuses the worker may write (mirrors ``clips_status_check``).
CLIP_STATUSES = frozenset({"pending", "processing", "ready", "failed"})


class ClipsPersistenceError(RuntimeError):
    """Clip rows could not be written to the database."""


def _as_job_uuid(job_id: str) -> str:
    """Validates the job id shape so a bad value can never widen the DELETE scope."""
    value = str(job_id or "")
    if not _UUID_RE.match(value):
        raise ValueError("clip store requires a UUID job id")
    try:
        UUID(value)
    except ValueError as exc:
        raise ValueError("clip store requires a UUID job id") from exc
    return value


class SupabaseClipStore:
    """Persists detected clips for one job (service-role client)."""

    def __init__(self, client: Client) -> None:
        self._client = client

    async def save_clips(self, job_id: str, clips: list[ScoredClip]) -> int:
        """Replaces the clip set of ``job_id`` with ``clips``; returns row count.

        Idempotent per job: a retry of the analysis replaces the same job's
        previous rows instead of duplicating them, and no other job's rows
        are read, deleted or written.
        """
        uuid_job = _as_job_uuid(job_id)
        rows = [self._row(uuid_job, index, clip) for index, clip in enumerate(clips)]
        try:
            # Delete ONLY this job's clips, then insert the new set.
            await self._client.table(CLIPS_TABLE).delete().eq("job_id", uuid_job).execute()
            if rows:
                await self._client.table(CLIPS_TABLE).insert(rows).execute()
        except Exception as exc:  # noqa: BLE001 — transport boundary
            logger.warning("clip persistence failed for job %s: %s", uuid_job, exc.__class__.__name__)
            raise ClipsPersistenceError("clip rows could not be saved") from exc
        return len(rows)

    @staticmethod
    def _row(job_id: str, index: int, clip: ScoredClip) -> dict[str, Any]:
        # Phase 5B: persist the clip's real word timings (ABSOLUTE audio
        # seconds) so the rendering stage can burn subtitles without
        # re-transcribing. None when the window has no usable words.
        captions = (
            {"words": [{"w": t.word, "s": t.start, "e": t.end} for t in clip.words]}
            if clip.words
            else None
        )
        return {
            "job_id": job_id,
            "title": clip.title,
            "start_time": clip.start,
            "end_time": clip.end,
            # duration is generated by the DB (end_time - start_time)
            "score": clip.score,
            "scoring": clip.scoring,
            "captions": captions,
            "sort_order": index,
            "status": "pending",
            "storage_path": None,
        }

    async def list_clips(self, job_id: str) -> list[dict[str, Any]]:
        """Returns the job's clips in sort order (the render input set).

        Scoped to the single job; raises :class:`ClipsPersistenceError` on a
        transport failure.
        """
        uuid_job = _as_job_uuid(job_id)
        try:
            result = await (
                self._client.table(CLIPS_TABLE)
                .select("id,title,start_time,end_time,status,storage_path,sort_order,captions")
                .eq("job_id", uuid_job)
                .order("sort_order")
                .execute()
            )
            return list(result.data or [])
        except Exception as exc:  # noqa: BLE001 — transport boundary
            logger.warning("clip list failed for job %s: %s", uuid_job, exc.__class__.__name__)
            raise ClipsPersistenceError("clip rows could not be loaded") from exc

    async def mark_clip(
        self,
        job_id: str,
        clip_id: str,
        status: str,
        storage_path: str | None = None,
    ) -> bool:
        """Moves ONE clip of ONE job to ``status`` (optionally setting ``storage_path``).

        The update is scoped to ``(id, job_id)`` — a stale worker can never
        mark another job's clip. Returns True when a row was updated, False
        when the clip no longer exists or is no longer owned (the caller
        must then treat it as lost ownership and abort).
        """
        uuid_job = _as_job_uuid(job_id)
        if not _UUID_RE.match(str(clip_id or "")):
            raise ValueError("clip store requires a UUID clip id")
        if status not in CLIP_STATUSES:
            raise ValueError(f"unknown clip status: {status!r}")
        values: dict[str, Any] = {"status": status}
        if storage_path is not None:
            values["storage_path"] = storage_path
        try:
            result = await (
                self._client.table(CLIPS_TABLE)
                .update(values)
                .eq("id", str(clip_id))
                .eq("job_id", uuid_job)
                .execute()
            )
            return bool(result.data)
        except Exception as exc:  # noqa: BLE001 — transport boundary
            logger.warning("clip update failed for job %s: %s", uuid_job, exc.__class__.__name__)
            raise ClipsPersistenceError("clip row could not be updated") from exc
